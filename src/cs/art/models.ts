/**
 * Weapon models: layered 2D parts (side view, muzzle / blade tip to the right, y down).
 * 'skin' parts take the skin texture; metal/dark/rubber/wood stay plain.
 * depth = extrusion thickness, z = centre offset, both in model units, for the 3D viewer.
 */
import type { WeaponModel, WeaponPart } from '../contract';
import { shape, rect, ellipse, part, spline, rotate, translate, Pt, PtR } from './geom';

type Builder = () => WeaponModel;
type M = WeaponPart['material'];

// ------------------------------------------------------------------ building blocks
const S = (pts: PtR[], r = 0) => shape(pts, r);

function capsule(x0: number, y0: number, x1: number, y1: number, r: number, n = 10): Pt[] {
  const a = Math.atan2(y1 - y0, x1 - x0);
  const out: Pt[] = [];
  for (let i = 0; i <= n; i++) { const t = a - Math.PI / 2 + (i / n) * Math.PI; out.push([x1 + Math.cos(t) * r, y1 + Math.sin(t) * r]); }
  for (let i = 0; i <= n; i++) { const t = a + Math.PI / 2 + (i / n) * Math.PI; out.push([x0 + Math.cos(t) * r, y0 + Math.sin(t) * r]); }
  return out;
}

/** Trigger guard ring + trigger. x,y = top-left of the guard, w,h size. */
function guard(x: number, y: number, w: number, h: number, mat: M = 'metal', layer = 2): WeaponPart[] {
  const t = Math.max(3, h * 0.24);
  return [
    part('guard', [S([[x, y], [x + w, y], [x + w - 2, y + h * 0.55, h * 0.3], [x + w * 0.72, y + h, h * 0.4], [x + 4, y + h, h * 0.35], [x, y + h * 0.6]], 3),
      S([[x + t * 0.9, y + 1], [x + w - t * 1.2, y + 1], [x + w - t * 1.3, y + h * 0.5, h * 0.25], [x + w * 0.68, y + h - t, h * 0.3], [x + t * 1.3, y + h - t, h * 0.25], [x + t, y + h * 0.55]], 2)], mat, 8, layer),
    part('trigger', S([[x + w * 0.38, y], [x + w * 0.38 + 6, y], [x + w * 0.38 + 8, y + h * 0.42, 3], [x + w * 0.38 + 3, y + h * 0.7, 2], [x + w * 0.38 + 1, y + h * 0.45]]), 'dark', 4, layer - 1),
  ];
}

/** Rifle scope: tube, bells, turret, mounts. Centre line y, from x0 (eyepiece) to x1 (objective). */
function scope(x0: number, x1: number, y: number, r: number, layer = 6): WeaponPart[] {
  const L = x1 - x0;
  const body = S([
    [x0, y - r * 1.25, 2], [x0 + L * 0.16, y - r * 1.25, 2], [x0 + L * 0.26, y - r * 0.82, 3], [x0 + L * 0.66, y - r * 0.82, 3],
    [x0 + L * 0.8, y - r * 1.5, 3], [x1, y - r * 1.5, 2], [x1, y + r * 1.5, 2], [x0 + L * 0.8, y + r * 1.5, 3],
    [x0 + L * 0.66, y + r * 0.82, 3], [x0 + L * 0.26, y + r * 0.82, 3], [x0 + L * 0.16, y + r * 1.25, 2], [x0, y + r * 1.25, 2],
  ]);
  const tx = x0 + L * 0.42;
  return [
    part('scope-mount-a', S([[x0 + L * 0.24, y], [x0 + L * 0.34, y], [x0 + L * 0.36, y + r * 2.3], [x0 + L * 0.22, y + r * 2.3]], 2), 'dark', 10, layer - 1),
    part('scope-mount-b', S([[x0 + L * 0.58, y], [x0 + L * 0.68, y], [x0 + L * 0.7, y + r * 2.3], [x0 + L * 0.56, y + r * 2.3]], 2), 'dark', 10, layer - 1),
    part('scope', body, 'dark', r * 2, layer),
    part('scope-turret', S([[tx - r * 0.7, y - r * 0.8], [tx - r * 0.6, y - r * 1.9, 2], [tx + r * 0.6, y - r * 1.9, 2], [tx + r * 0.7, y - r * 0.8]]), 'metal', r * 1.4, layer + 1),
    part('scope-lens', S([[x1 - 3, y - r * 1.3], [x1 + 1.5, y - r * 1.2], [x1 + 1.5, y + r * 1.2], [x1 - 3, y + r * 1.3]], 1), 'metal', r * 2.4, layer + 1),
    part('scope-band', rect(x0 + L * 0.45, y - r * 0.84, L * 0.1, r * 1.68, 1), 'metal', r * 1.7, layer + 1),
  ];
}

/** Picatinny rail with teeth on top. */
function rail(x0: number, x1: number, y: number, h = 7, layer = 5): WeaponPart {
  const pts: Pt[] = [[x0, y + h]];
  const tooth = 7;
  for (let x = x0; x < x1 - 2; x += tooth) {
    pts.push([x, y + 2.5], [x + 1.2, y], [x + tooth * 0.55, y], [x + tooth * 0.55 + 1.2, y + 2.5]);
  }
  pts.push([x1, y + 2.5], [x1, y + h]);
  return part('rail', pts, 'dark', 12, layer);
}

/** Row of slots/vents as one dark part on top of something. */
function slots(x0: number, y: number, n: number, w: number, h: number, gap: number, layer: number, z = 0): WeaponPart {
  const rings: Pt[][] = [];
  for (let i = 0; i < n; i++) rings.push(rect(x0 + i * (w + gap), y, w, h, Math.min(w, h) / 2));
  return part('vents', rings, 'dark', 2, layer, z);
}

/** Barrel with a slight taper. */
function barrel(x0: number, x1: number, y: number, r0: number, r1 = r0 * 0.85, mat: M = 'metal', layer = 1): WeaponPart {
  return part('barrel', S([[x0, y - r0], [x1, y - r1, 1], [x1, y + r1, 1], [x0, y + r0]]), mat, r0 * 2, layer);
}

function muzzleBrake(x: number, y: number, len: number, r: number, layer = 2): WeaponPart[] {
  return [
    part('muzzle', S([[x, y - r], [x + len, y - r, 2], [x + len, y + r, 2], [x, y + r]], 1), 'dark', r * 2, layer),
    part('muzzle-ports', [rect(x + len * 0.2, y - r * 0.55, len * 0.18, r * 1.1, 1), rect(x + len * 0.55, y - r * 0.55, len * 0.18, r * 1.1, 1)], 'metal', 2, layer + 1, r),
  ];
}

const model = (w: number, h: number, parts: WeaponPart[]): WeaponModel => ({ box: [w, h], parts });

