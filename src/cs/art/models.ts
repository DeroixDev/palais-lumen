/** Fallback per kind for unknown ids. */
const KIND_FALLBACK: Record<string, string> = {
  pistol: 'p9', smg: 'mk5', rifle: 'ar7', sniper: 'awlong', shotgun: 'pumpe12', heavy: 'brecher', knife: 'krallmesser', gloves: 'sporthandschuhe',
};

const cache = new Map<string, WeaponModel>();

export function buildModel(id: string, kind?: string): WeaponModel {
  let m = cache.get(id);
  if (m) return m;
  const b = BUILDERS[id] ?? BUILDERS[KIND_FALLBACK[kind ?? ''] ?? 'ar7'];
  m = b();
  m.parts.sort((a, b2) => a.layer - b2.layer);
  cache.set(id, m);
  return m;
}

